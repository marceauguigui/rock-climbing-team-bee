#!/usr/bin/env python3
"""Generate a MuJoCo `wall.xml` (board + holds) from a climbing-sim wall JSON.

Usage:
    python make_wall_xml.py path/to/N2.json -o wall.xml [--collide]

JSON form: {"holds": [{"col": 3, "row": 10}, ...], "start": {"left_hand": {"col": 3, "row": 10}, ...}}

The constants and frames are those of climbing_sim/wall.py:
x to the right, y INTO the wall, z up; origin at the bottom-left corner of the front face;
the board occupies 0 <= y <= 10 mm, the climber is on the y < 0 side.
"""
import argparse
import json
import pathlib

# --- constants copied from wall.py (metres) ---
WALL_WIDTH, WALL_HEIGHT, WALL_THICKNESS = 0.800, 1.400, 0.010
HOLE_PITCH = 0.015
GRID_COLS, GRID_ROWS = 52, 93
GRID_X0, GRID_Z0 = 0.0175, 0.010
SOCKET_OUT, SOCKET_BELOW = 0.026, 0.014


def hole_xz(col: int, row: int) -> tuple[float, float]:
    if not (0 <= col < GRID_COLS and 0 <= row < GRID_ROWS):
        raise ValueError(f"hole ({col}, {row}) outside the {GRID_COLS} x {GRID_ROWS} grid")
    return GRID_X0 + col * HOLE_PITCH, GRID_Z0 + row * HOLE_PITCH


def socket_pos(col: int, row: int) -> tuple[float, float, float]:
    """Socket centre of the hold whose LEFT hole is (col, row); right hole is (col + 2, row)."""
    xl, z = hole_xz(col, row)
    xr, _ = hole_xz(col + 2, row)
    return (xl + xr) / 2, -SOCKET_OUT, z - SOCKET_BELOW


def build_xml(wall: dict, collide: bool) -> str:
    holds = []
    seen = set()
    for h in wall.get("holds", []):
        k = (int(h["col"]), int(h["row"]))
        if k not in seen:
            seen.add(k)
            holds.append(k)
    start = {limb: (int(h["col"]), int(h["row"])) for limb, h in wall.get("start", {}).items()}
    for k in start.values():            # a start hold missing from the list is added (as in Wall.from_dict)
        if k not in seen:
            seen.add(k)
            holds.insert(0, k)
    start_of = {}
    for limb, k in start.items():
        start_of.setdefault(k, []).append(limb)

    contact = 'contype="1" conaffinity="1"' if collide else 'contype="0" conaffinity="0"'
    out = []
    out.append('<mujoco model="wall">')
    out.append('    <!-- Generated by make_wall_xml.py: board + holds. Do not edit by hand. -->')
    out.append('    <asset>')
    out.append('        <material name="board" rgba="0.80 0.68 0.50 1" />')
    out.append('        <material name="hold" rgba="0.95 0.45 0.10 1" />')
    out.append('        <material name="hold_start" rgba="0.15 0.75 0.30 1" />')
    out.append('    </asset>')
    out.append('    <worldbody>')
    out.append('        <body name="wall" pos="0 0 0">')
    out.append(
        f'            <geom name="board" type="box" material="board" '
        f'size="{WALL_WIDTH/2:.4f} {WALL_THICKNESS/2:.4f} {WALL_HEIGHT/2:.4f}" '
        f'pos="{WALL_WIDTH/2:.4f} {WALL_THICKNESS/2:.4f} {WALL_HEIGHT/2:.4f}" friction="1 0.005 0.0001" />')
    for col, row in holds:
        x, y, z = socket_pos(col, row)
        name = f"hold_{col}_{row}"
        is_start = (col, row) in start_of
        mat = "hold_start" if is_start else "hold"
        # Simplified hold body: a small box between the wall face and the socket, centred on the bolt axis
        # (the real part has a spherical socket, which is not modelled here).
        xb = x
        zb = z + SOCKET_BELOW
        depth = SOCKET_OUT
        out.append(f'            <body name="{name}" pos="{xb:.5f} 0 {zb:.5f}">')
        out.append(
            f'                <geom name="{name}_body" type="box" material="{mat}" {contact} '
            f'size="0.0150 {depth/2:.4f} 0.0070" pos="0 {-depth/2:.4f} 0" />')
        # Site at the socket centre: where a ball end rests when hooked (use it for rewards / grasp constraints).
        out.append(
            f'                <site name="socket_{col}_{row}" pos="0 {-SOCKET_OUT:.5f} {-SOCKET_BELOW:.5f}" '
            f'size="0.004" rgba="1 1 0 1" />')
        out.append('            </body>')
    out.append('        </body>')
    out.append('    </worldbody>')
    out.append('</mujoco>')
    return "\n".join(out) + "\n", holds, start_of


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("wall_json", type=pathlib.Path)
    ap.add_argument("-o", "--output", type=pathlib.Path, default=pathlib.Path("wall.xml"))
    ap.add_argument("--collide", action="store_true",
                    help="make the simplified hold bodies collidable (off by default: they would block the "
                         "robot's ball ends, which must reach the socket centre)")
    args = ap.parse_args()

    wall = json.loads(args.wall_json.read_text())
    xml, holds, start_of = build_xml(wall, args.collide)
    args.output.write_text(xml)
    print(f"{args.output}: {len(holds)} holds")
    for (col, row), limbs in start_of.items():
        x, y, z = socket_pos(col, row)
        print(f"  start {', '.join(limbs)}: hold ({col}, {row}), socket at ({x:.4f}, {y:.4f}, {z:.4f}) m")


if __name__ == "__main__":
    main()